def safe_literal_eval(s):
    """Safely evaluate string representation of Python literals."""
    if pd.isna(s) or s == '' or s == 'syntax error':
        return []
    
    try:
        if isinstance(s, str):
            s = s.strip()
            if s == '[]':
                return []
            elif s.startswith('[') and s.endswith(']'):
                return ast.literal_eval(s)
            else:
                return []
        return []
    except (ValueError, SyntaxError):
        return []


def majority_vote(parsed_outputs):
    """
    Perform majority vote on a list of parsed outputs, filtering out syntax errors.
    
    Args:
        parsed_outputs: List of parsed outputs (strings like '[A, B]', 'syntax error', etc.)
    
    Returns:
        String representing the majority vote result
    
    Examples with K=3:
        ['[A, B]', '[B, C]', 'syntax error'] -> '[A, B]' or '[B, C]' (tie)
        ['[A, B]', '[A, B]', '[A, B, C]'] -> '[A, B]'
        ['[A]', '[A]', '[A, B, C]'] -> '[A]'
        ['[]', '[]', '[A]'] -> '[]'
    """
    if not parsed_outputs: # if parsed_outputs is empty, return []
        return '[]'
    
    # Filter out syntax errors
    valid_outputs = [output for output in parsed_outputs if output != 'syntax error']
    
    # If no valid outputs, return []
    if not valid_outputs:
        return '[]'
    
    # Count occurrences of each valid parsed output
    output_counts = Counter(valid_outputs)
    
    # Find the most common output
    most_common = output_counts.most_common(1)[0][0]
    
    return most_common


def cot_backup_filter(majority_result, sampled_paths, pruning_column, true_label, use_cot_backup):
    """
    Apply CoT backup logic based on majority vote result and pruning column.
    
    Args:
        majority_result: The result from majority voting
        sampled_paths: DataFrame containing the sampled paths for this sample
        pruning_column: The column used for pruning/voting
        true_label: The correct answer for this sample
        use_cot_backup: Whether CoT backup is enabled
    
    Returns:
        tuple: (final_result, used_cot_backup, backup_reason)
    """
    used_cot_backup = False
    backup_reason = None
    final_result = majority_result
    
    if not use_cot_backup or 'cot_correctness' not in sampled_paths.columns:
        return final_result, used_cot_backup, backup_reason
    
    # Get CoT correctness for this sample (should be same for all paths)
    cot_correct = sampled_paths.iloc[0]['cot_correctness']
    should_use_backup = False
    
    if pd.notna(cot_correct) and cot_correct:        
        # Case 1: Existence pruning - if result is empty, use CoT as backup
        if pruning_column == 'existence_pruning_result' and majority_result == '[]':
            should_use_backup = True
            backup_reason = 'existence_empty'
        
        # Case 2: Uniqueness pruning - if result has more than 1 element, use CoT as backup
        if pruning_column == 'uniqueness_pruning_result':
            try:
                parsed_result = safe_literal_eval(majority_result)
                if isinstance(parsed_result, list) and len(parsed_result) > 1:
                    should_use_backup = True
                    backup_reason = 'uniqueness_multiple'
            except:
                pass
        
        # Case 3: Combined pruning (existence + uniqueness) - empty result
        if pruning_column == 'existence_uniqueness_pruning_result' and majority_result == '[]':
            should_use_backup = True
            backup_reason = 'combined_empty'
        
        # Use CoT result as backup if any condition is met
        if should_use_backup:
            final_result = f'[{true_label}]'
            used_cot_backup = True
    
    return final_result, used_cot_backup, backup_reason


def calculate_accuracy_for_k_paths(df, k, dataset, random_sample=False, seed=None, use_pruned=False, pruning_column='parsed_output', use_cot_backup=False):
    """Calculate accuracy using majority vote on k paths for each sample."""
    if seed is not None:
        random.seed(seed)
    
    results = []
    
    # Group by sample_id
    for sample_id, group in df.groupby('sample_id'):
        group_sorted = group.sort_values('path_index')
        
        if random_sample:
            # Always randomly sample k paths (or all available if fewer than k)
            n_sample = min(k, len(group_sorted))
            sampled_paths = group_sorted.sample(n=n_sample, random_state=seed)
        else:
            # Take first k paths
            sampled_paths = group_sorted.head(k)
        
        if len(sampled_paths) == 0:
            continue
            
        # Get true label (should be same for all paths of this sample)
        true_label = sampled_paths.iloc[0]['true_label']
        
        # Extract parsed outputs as strings (no preprocessing)
        parsed_outputs = []
        for _, row in sampled_paths.iterrows():
            # Use the specified pruning column (default: 'parsed_output')
            if pruning_column in row and pd.notna(row[pruning_column]):
                parsed_output = str(row[pruning_column])
            else:
                parsed_output = 'syntax error'
            parsed_outputs.append(parsed_output)
        
        # Perform majority vote
        majority_result = majority_vote(parsed_outputs)
        
        # Apply CoT backup filter
        majority_result, used_cot_backup, backup_reason = cot_backup_filter(
            majority_result, sampled_paths, pruning_column, true_label, use_cot_backup)
        
        # Determine correctness based on dataset
        is_correct = is_majority_vote_correct(majority_result, true_label, dataset)
        
        results.append({
            'sample_id': sample_id,
            'k_paths': k,
            'majority_vote_result': majority_result,
            'true_label': true_label,
            'is_correct': is_correct,
            'total_paths_used': len(parsed_outputs),
            'simulation_seed': seed if random_sample else None,
            'used_cot_backup': used_cot_backup,
            'backup_reason': backup_reason
        })
    
    return results


def is_majority_vote_correct(majority_result, true_label, dataset):
    """Determine if majority vote result is correct based on dataset format."""
    if majority_result == 'syntax error':  # Syntax error is always incorrect
        return False
    
    try:
        # Parse the majority result to extract the answer
        parsed_result = safe_literal_eval(majority_result)
        
        if not parsed_result or len(parsed_result) != 1:  # Should have exactly one answer
            return False
        
        predicted_answer = parsed_result[0]
        
        # Handle different dataset formats
        if dataset.upper() == 'AR-LSAT':
            # AR-LSAT: numeric comparison
            return int(predicted_answer) == int(true_label)
        elif dataset.upper() in ['PROOFWRITER', 'FOLIO']:
            # ProofWriter/FOLIO: mapping between boolean and letters
            return (predicted_answer == "True" and true_label == "A") or \
                   (predicted_answer == "False" and true_label == "B") or \
                   (predicted_answer == "Unknown" and true_label == "C")
        elif dataset.upper() == 'PRONTOQA':
            # ProntoQA: mapping between boolean and letters
            return (predicted_answer == "True" and true_label == "A") or \
                   (predicted_answer == "False" and true_label == "B")
        elif dataset.upper() == 'LOGICALDEDUCTION':
            # LogicalDeduction: direct letter comparison
            return str(predicted_answer) == str(true_label)
        else:
            # Default: string comparison
            return str(predicted_answer) == str(true_label)
    except (ValueError, TypeError):
        return False


def run_simulation_analysis(df, max_paths=30, num_simulations=50, pruning_column='parsed_output', use_cot_backup=False):
    """Run multiple simulation analysis with random sampling and error bars."""
    if df.empty:
        return pd.DataFrame(), pd.DataFrame()
    
    # Get dataset name
    dataset = df['dataset'].iloc[0] if 'dataset' in df.columns else 'unknown'
    
    # Determine actual max paths available
    max_available_paths = df.groupby('sample_id')['path_index'].max().max() + 1
    actual_max_paths = min(max_paths, max_available_paths)
    
    print(f"Dataset: {dataset}")
    print(f"Max paths requested: {max_paths}")
    print(f"Max paths available: {max_available_paths}")
    print(f"Using max paths: {actual_max_paths}")
    print(f"Number of simulations: {num_simulations}")
    if use_cot_backup:
        print(f"CoT backup enabled for existence_uniqueness_pruning_result")
    
    # Generate k values: 1, 2, 3, 4, ..., max_paths
    k_values = list(range(1, actual_max_paths + 1))
    
    print(f"Testing k values: {k_values}")
    
    all_results = []
    simulation_results = []
    
    for k in k_values:
        print(f"Processing k={k} paths...")
        k_accuracies = []
        k_cot_backup_usage = []
        
        for sim in range(num_simulations):
            # Always use random sampling for all k values
            seed = sim
            
            k_results = calculate_accuracy_for_k_paths(df, k, dataset, 
                                                     random_sample=True, 
                                                     seed=seed,
                                                     pruning_column=pruning_column,
                                                     use_cot_backup=use_cot_backup)
            all_results.extend(k_results)
            
            # Calculate accuracy and CoT backup usage for this simulation
            if k_results:
                accuracy = sum(r['is_correct'] for r in k_results) / len(k_results)
                cot_backup_used = sum(r.get('used_cot_backup', False) for r in k_results)
                
                # Count backup usage by reason
                backup_reasons = {}
                for r in k_results:
                    if r.get('used_cot_backup', False) and r.get('backup_reason'):
                        reason = r['backup_reason']
                        backup_reasons[reason] = backup_reasons.get(reason, 0) + 1
                
                k_accuracies.append(accuracy)
                k_cot_backup_usage.append(cot_backup_used)
                
                sim_result = {
                    'k_paths': k,
                    'simulation': sim,
                    'accuracy': accuracy,
                    'total_samples': len(k_results),
                    'correct_samples': sum(r['is_correct'] for r in k_results),
                    'cot_backup_used': cot_backup_used
                }
                
                # Add backup reason counts
                for reason, count in backup_reasons.items():
                    sim_result[f'backup_{reason}'] = count
                
                simulation_results.append(sim_result)
        
        if use_cot_backup and k_cot_backup_usage:
            avg_cot_usage = np.mean(k_cot_backup_usage)
            print(f"  k={k}: mean={np.mean(k_accuracies):.4f}, std={np.std(k_accuracies):.4f}, avg_cot_backup={avg_cot_usage:.1f}")
        else:
            print(f"  k={k}: mean={np.mean(k_accuracies):.4f}, std={np.std(k_accuracies):.4f}")
    
    # Convert to DataFrames
    results_df = pd.DataFrame(all_results)
    simulation_df = pd.DataFrame(simulation_results)
    
    return results_df, simulation_df


def run_ablation_analysis(df, max_paths=30, pruning_column='parsed_output'):
    """Run complete ablation analysis for different values of k (original deterministic version)."""
    if df.empty:
        return pd.DataFrame()
    
    # Get dataset name
    dataset = df['dataset'].iloc[0] if 'dataset' in df.columns else 'unknown'
    
    # Determine actual max paths available
    max_available_paths = df.groupby('sample_id')['path_index'].max().max() + 1
    actual_max_paths = min(max_paths, max_available_paths)
    
    print(f"Dataset: {dataset}")
    print(f"Max paths requested: {max_paths}")
    print(f"Max paths available: {max_available_paths}")
    print(f"Using max paths: {actual_max_paths}")
    
    # Generate k values: 1, 2, 3, 4, ..., max_paths
    k_values = list(range(1, actual_max_paths + 1))
    
    print(f"Testing k values: {k_values}")
    
    all_results = []
    
    for k in k_values:
        print(f"Processing k={k} paths...")
        k_results = calculate_accuracy_for_k_paths(df, k, dataset, pruning_column=pruning_column)
        all_results.extend(k_results)
    
    # Convert to DataFrame
    results_df = pd.DataFrame(all_results)
    
    # Calculate summary statistics
    summary_stats = []
    for k in k_values:
        k_data = results_df[results_df['k_paths'] == k]
        if len(k_data) > 0:
            accuracy = k_data['is_correct'].mean()
            total_samples = len(k_data)
            correct_samples = k_data['is_correct'].sum()
            
            summary_stats.append({
                'k_paths': k,
                'total_samples': total_samples,
                'correct_samples': correct_samples,
                'accuracy': accuracy
            })
    
    summary_df = pd.DataFrame(summary_stats)
    
    return results_df, summary_df


def plot_error_shade(simulation_df, output_file=None, csv_file=None, title_suffix=""):
    """Create error shade plot from simulation results using standard deviation."""
    # Calculate statistics for each k
    stats = simulation_df.groupby('k_paths')['accuracy'].agg([
        'mean', 'std', 'count'
    ]).reset_index()
    
    # Use standard deviation for shading
    stats['upper'] = stats['mean'] + stats['std']
    stats['lower'] = stats['mean'] - stats['std']
    
    # Set up the plot style
    try:
        plt.style.use('seaborn-v0_8')
    except:
        try:
            plt.style.use('seaborn')
        except:
            pass  # Use default style
    
    fig, ax = plt.subplots(figsize=(6, 6))
    
    # Create the main line plot
    ax.plot(stats['k_paths'], stats['mean'], 
            marker='o', linewidth=2.5, markersize=6,
            color='steelblue', alpha=0.9, label='Mean Accuracy')
    
    # Add shaded error region (±1 standard deviation)
    ax.fill_between(stats['k_paths'], stats['lower'], stats['upper'], 
                    alpha=0.3, color='steelblue', 
                    label='±1 Standard Deviation')
    
    # Customize the plot
    ax.set_xlabel('Number of Paths (K)', fontsize=12, fontweight='bold')
    ax.set_ylabel('Accuracy', fontsize=12, fontweight='bold')
    # ax.set_title('Majority Vote Accuracy vs Number of Paths\n(with Standard Deviation)', 
                #  fontsize=14, fontweight='bold', pad=20)
    
    # set xlim to 1 to max_paths
    ax.set_xlim(1, stats['k_paths'].max())
    # set x ticks to 1 to max_paths
    ax.set_xticks(np.arange(1, stats['k_paths'].max() + 1))
    # Format axes
    ax.grid(True, alpha=0.3)
    ax.set_ylim(max(0, min(stats['lower']) * 0.95), 
                max(stats['upper']) * 1.05)
    
    # Add legend
    ax.legend(loc='best', framealpha=0.9)
    
    # Note: Removed value labels on points as requested
    
    plt.tight_layout()
    
    # Save plot
    if output_file:
        # Use PDF format and add input file name split by / and take the last part before .csv
        base_name = os.path.basename(csv_file).split('/')[-1].split('.csv')[0]
        pdf_output = f"{base_name}_path_ablation.pdf"
        plt.savefig(pdf_output, format='pdf', dpi=300, bbox_inches='tight')
        print(f"Plot saved to: {pdf_output}")
    
    plt.show()
    
    return fig, ax


