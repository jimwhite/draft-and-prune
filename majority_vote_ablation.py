def generate_pruning_comparison_table(df, csv_file, k=20, num_simulations=10, use_cot_backup=False):
    """Generate comparison table for different pruning methods at k=5."""
    print(f"\n{'='*60}")
    print(f"PRUNING COMPARISON TABLE (k={k}, {num_simulations} simulations)")
    print(f"{'='*60}")
    
    dataset = df['dataset'].iloc[0] if 'dataset' in df.columns else 'unknown'
    
    # Define the pruning methods and their corresponding columns
    methods = [
        ('None (use parsed_output only)', 'parsed_output'),
        ('P1 (existence)', 'existence_pruning_result'),
        ('P2 (uniqueness)', 'uniqueness_pruning_result'),
        ('P1+P2', 'existence_uniqueness_pruning_result')
    ]
    
    results_table = []
    
    for method_name, column_name in methods:
        print(f"\nProcessing {method_name}...")
        
        # Check if column exists
        if column_name not in df.columns:
            print(f"Warning: Column {column_name} not found, skipping...")
            continue
        
        # Run simulations for this method
        accuracies = []
        for sim in range(num_simulations):
            seed = sim
            k_results = calculate_accuracy_for_k_paths(df, k, dataset, 
                                                     random_sample=True, 
                                                     seed=seed,
                                                     pruning_column=column_name,
                                                     use_cot_backup=use_cot_backup)
            
            if k_results:
                accuracy = sum(r['is_correct'] for r in k_results) / len(k_results)
                accuracies.append(accuracy)
        
        if accuracies:
            mean_acc = np.mean(accuracies)
            std_acc = np.std(accuracies)
            results_table.append({
                'Method': method_name,
                'Column': column_name,
                'Mean_Accuracy': mean_acc,
                'Std_Accuracy': std_acc,
                'Accuracies': accuracies
            })
            print(f"  Mean: {mean_acc:.4f}, Std: {std_acc:.4f}")
    
    # Create and display table
    if results_table:
        print(f"\n{'='*60}")
        print("SUMMARY TABLE")
        print(f"{'='*60}")
        print(f"{'Method':<35} {'Accuracy':<15} {'Std':<10}")
        print("-" * 60)
        
        for result in results_table:
            method_short = result['Method'].split(' (')[0]  # Shorten method name
            print(f"{method_short:<35} {result['Mean_Accuracy']:<15.4f} {result['Std_Accuracy']:<10.4f}")
        
        # Save detailed results to CSV
        base_name = os.path.splitext(os.path.basename(csv_file))[0]
        output_file = f"{base_name}_pruning_comparison_k{k}.csv"
        
        # Create detailed CSV with all simulation results
        detailed_data = []
        for result in results_table:
            for sim_idx, acc in enumerate(result['Accuracies']):
                detailed_data.append({
                    'Method': result['Method'],
                    'Column': result['Column'],
                    'Simulation': sim_idx,
                    'Accuracy': acc
                })
        
        detailed_df = pd.DataFrame(detailed_data)
        detailed_df.to_csv(output_file, index=False)
        print(f"\nDetailed results saved to: {output_file}")
        
        # Create summary CSV
        summary_file = f"{base_name}_pruning_summary_k{k}.csv"
        summary_data = []
        for result in results_table:
            summary_data.append({
                'Method': result['Method'],
                'Column': result['Column'],
                'Mean_Accuracy': result['Mean_Accuracy'],
                'Std_Accuracy': result['Std_Accuracy'],
                'K_Paths': k,
                'Num_Simulations': num_simulations
            })
        
        summary_df = pd.DataFrame(summary_data)
        summary_df.to_csv(summary_file, index=False)
        print(f"Summary table saved to: {summary_file}")
        
        return summary_df
    
    return None


def process_single_file(csv_file, max_paths=30, num_simulations=50, use_simulations=False, enable_cot_backup=False):
    """Process a single CSV file and return results for both pruning methods."""
    print(f"\nProcessing file: {csv_file}")
    
    # Load data
    try:
        df = pd.read_csv(csv_file)
    except Exception as e:
        print(f"Error loading {csv_file}: {e}")
        return None, None, None, None, None, None, None
    
    print(f"Loaded {len(df)} rows")
    
    # Basic info
    if 'sample_id' not in df.columns:
        print("Error: 'sample_id' column not found")
        return None, None, None, None, None, None, None
    
    num_samples = df['sample_id'].nunique()
    num_paths_per_sample = df.groupby('sample_id').size()
    
    print(f"Number of samples: {num_samples}")
    print(f"Paths per sample - min: {num_paths_per_sample.min()}, max: {num_paths_per_sample.max()}, mean: {num_paths_per_sample.mean():.1f}")
    
    # Check if existence_uniqueness_pruning_result column exists
    has_pruning_column = 'existence_uniqueness_pruning_result' in df.columns
    has_cot_column = 'cot_correctness' in df.columns
    print(f"Has existence_uniqueness_pruning_result column: {has_pruning_column}")
    print(f"Has cot_correctness column: {has_cot_column}")
    
    # CoT backup is only enabled for existence_uniqueness_pruning_result when both columns exist
    use_cot_backup_for_pruning = enable_cot_backup and has_pruning_column and has_cot_column
    if enable_cot_backup and not has_cot_column:
        print("Warning: CoT backup requested but cot_correctness column not found")
    
    # Run analysis for parsed_output
    print("\n=== Processing with parsed_output ===")
    if use_simulations:
        results_df1, simulation_df1 = run_simulation_analysis(df, max_paths, num_simulations, 'parsed_output', use_cot_backup=False)
        
        # Calculate summary statistics from simulations
        summary_stats1 = simulation_df1.groupby('k_paths')['accuracy'].agg([
            'mean', 'std', 'count'
        ]).reset_index()
        summary_stats1.rename(columns={'mean': 'accuracy'}, inplace=True)
        summary_stats1['total_samples'] = num_samples
        summary_stats1['correct_samples'] = (summary_stats1['accuracy'] * num_samples).round().astype(int)
        
        summary_df1 = summary_stats1[['k_paths', 'total_samples', 'correct_samples', 'accuracy', 'std']]
    else:
        results_df1, summary_df1 = run_ablation_analysis(df, max_paths, 'parsed_output')
        simulation_df1 = None
    
    # Run analysis for existence_uniqueness_pruning_result if available
    results_df2, summary_df2, simulation_df2 = None, None, None
    if has_pruning_column:
        print("\n=== Processing with existence_uniqueness_pruning_result ===")
        if use_cot_backup_for_pruning:
            print("CoT backup will be used when majority vote result is empty")
        
        if use_simulations:
            results_df2, simulation_df2 = run_simulation_analysis(df, max_paths, num_simulations, 
                                                                 'existence_uniqueness_pruning_result', 
                                                                 use_cot_backup=use_cot_backup_for_pruning)
            
            # Calculate summary statistics from simulations
            summary_stats2 = simulation_df2.groupby('k_paths')['accuracy'].agg([
                'mean', 'std', 'count'
            ]).reset_index()
            summary_stats2.rename(columns={'mean': 'accuracy'}, inplace=True)
            summary_stats2['total_samples'] = num_samples
            summary_stats2['correct_samples'] = (summary_stats2['accuracy'] * num_samples).round().astype(int)
            
            summary_df2 = summary_stats2[['k_paths', 'total_samples', 'correct_samples', 'accuracy', 'std']]
        else:
            results_df2, summary_df2 = run_ablation_analysis(df, max_paths, 'existence_uniqueness_pruning_result')
            simulation_df2 = None
    
    # Extract experiment info
    exp_info = {
        'experiment_id': df['experiment_id'].iloc[0] if 'experiment_id' in df.columns else 'unknown',
        'dataset': df['dataset'].iloc[0] if 'dataset' in df.columns else 'unknown',
        'total_samples': num_samples,
        'max_paths_per_sample': num_paths_per_sample.max()
    }
    
    return results_df1, summary_df1, simulation_df1, results_df2, summary_df2, simulation_df2, exp_info


